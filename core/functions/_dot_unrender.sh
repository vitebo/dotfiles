#!/usr/bin/env bash
# Undoes `_dot_render`: removes `target` when we generated it, moves
# `<target>.bak` back, then removes the parent dirs left empty. Stops at `$HOME`,
# `~/.config` and direct children of `$HOME`.
#
#   _dot_unrender "${HOME}/.config/aerospace/aerospace.toml"

_dot_unrender() {
    local target="$1"

    if [ -f "${target}" ] && [ ! -L "${target}" ] \
        && head -n 1 "${target}" | grep -qF "${DOT_RENDER_HEADER}"; then
        rm "${target}"
    elif [ -e "${target}" ] || [ -L "${target}" ]; then
        _dot_warn "Kept ${target}: not generated by dotfiles"
        return 0
    fi

    if [ -e "${target}.bak" ] && [ ! -e "${target}" ]; then
        mv "${target}.bak" "${target}"
        _dot_warn "Restored ${target} from ${target}.bak"
    fi

    local dir
    dir="$(dirname "${target}")"
    while [ "${dir}" != "${HOME}" ] && [ "${dir}" != "${HOME}/.config" ] \
        && [ "$(dirname "${dir}")" != "${HOME}" ] && [ -d "${dir}" ] \
        && [ -z "$(ls -A "${dir}")" ]; do
        rmdir "${dir}"
        dir="$(dirname "${dir}")"
    done
}
