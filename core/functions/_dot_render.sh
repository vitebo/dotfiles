#!/usr/bin/env bash
# Writes `target` from the `template`, replacing each `@DOT_<NAME>@` with the
# exported variable (fails when one isn't set). For config files that differ per
# device and whose app can't include another file; otherwise use `_dot_link`.
# The first line marks the file as generated (a `#` comment, so only for formats
# with `#` comments). An existing symlink is replaced, a file we didn't generate is
# moved to `<target>.bak`; an unchanged file is left alone.
#
#   _dot_render "${DOT_PACKAGE_DIR}/config/aerospace.toml" "${HOME}/.config/aerospace/aerospace.toml"

DOT_RENDER_HEADER="# Generated by dotfiles"

_dot_render() {
    local template="$1"
    local target="$2"
    local tmp

    mkdir -p "$(dirname "${target}")"
    tmp="${target}.dot-render"
    {
        echo "${DOT_RENDER_HEADER} from ${template#"${DOT_ROOT:-}/"}: edit that file, not this one"
        awk '{
            out = ""
            while (match($0, /@DOT_[A-Z0-9_]+@/)) {
                name = substr($0, RSTART + 1, RLENGTH - 2)
                if (!(name in ENVIRON)) {
                    print "  ✗ " name " is not set" > "/dev/stderr"
                    exit 1
                }
                out = out substr($0, 1, RSTART - 1) ENVIRON[name]
                $0 = substr($0, RSTART + RLENGTH)
            }
            print out $0
        }' "${template}"
    } > "${tmp}" || { rm -f "${tmp}"; return 1; }

    if [ -L "${target}" ]; then
        rm "${target}"
    elif [ -f "${target}" ] && cmp -s "${tmp}" "${target}"; then
        rm "${tmp}"
        return 0
    elif [ -e "${target}" ] && ! head -n 1 "${target}" | grep -qF "${DOT_RENDER_HEADER}"; then
        mv "${target}" "${target}.bak"
        _dot_warn "Existing ${target} moved to ${target}.bak"
    fi
    mv "${tmp}" "${target}"
}
